alter table public.listing_ratings enable row level security;

create policy listing_ratings_select_public on public.listing_ratings
  for select using (true);
-- Only someone who opened the listing, is not its owner, and names the real seller.
create policy listing_ratings_insert_visited on public.listing_ratings
  for insert with check (
    reviewer_user_id = auth.uid()
    and exists (select 1 from public.listing_views v where v.listing_id = listing_ratings.listing_id and v.viewer_user_id = auth.uid())
    and exists (select 1 from public.listings l where l.id = listing_ratings.listing_id and l.user_id = listing_ratings.seller_id and l.user_id <> auth.uid())
  );
create policy listing_ratings_update_own on public.listing_ratings
  for update using (reviewer_user_id = auth.uid()) with check (reviewer_user_id = auth.uid());

create trigger listing_ratings_updated_at
  before update on public.listing_ratings
  for each row execute function public.set_updated_at();

