-- ---------------------------------------------------------------------
-- 1) Roles on profiles + is_admin() helper
-- ---------------------------------------------------------------------
alter table public.profiles
  add column if not exists role text not null default 'user'
    check (role in ('user', 'merchant', 'admin')),
  add column if not exists merchant_status text not null default 'none'
    check (merchant_status in ('none', 'pending', 'active', 'rejected', 'suspended'));

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- profiles_update_own lets a user update their own row, so block self-promotion:
-- only an admin may change role / merchant_status.
-- SECURITY INVOKER on purpose: current_user must be the caller's role.
create or replace function public.guard_profile_role()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  -- Only requests coming from the app (anon/authenticated) are restricted; the
  -- dashboard SQL editor / service_role can still appoint the first admin.
  if (new.role is distinct from old.role or new.merchant_status is distinct from old.merchant_status)
     and current_user in ('anon', 'authenticated')
     and not public.is_admin() then
    raise exception 'ROLE_CHANGE_FORBIDDEN';
  end if;
  return new;
end;
$$;

drop trigger if exists profiles_guard_role on public.profiles;
create trigger profiles_guard_role
  before update on public.profiles
  for each row execute function public.guard_profile_role();

-- Admins can approve merchants / change roles on any profile.
create policy profiles_admin_update on public.profiles
  for update using (public.is_admin()) with check (public.is_admin());

-- Admins can read and moderate every listing (owners keep their existing policies).
create policy listings_admin_select on public.listings
  for select using (public.is_admin());
create policy listings_admin_update on public.listings
  for update using (public.is_admin()) with check (public.is_admin());
create policy listing_media_admin_select on public.listing_media
  for select using (public.is_admin());

-- ---------------------------------------------------------------------
-- 2) Merchant subscriptions + public store directory
-- ---------------------------------------------------------------------
create table if not exists public.merchant_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  plan_code text not null,
  status text not null default 'pending'
    check (status in ('pending', 'active', 'expired', 'suspended', 'cancelled')),
  max_products integer not null default 10 check (max_products >= 0),
  max_images_per_product integer not null default 10 check (max_images_per_product >= 0),
  can_use_store boolean not null default false,
  can_manage_products boolean not null default false,
  can_reply_to_chats boolean not null default false,
  starts_at timestamptz,
  ends_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists merchant_subscriptions_user_idx on public.merchant_subscriptions (user_id, created_at desc);
alter table public.merchant_subscriptions enable row level security;

create policy merchant_subscriptions_select_own on public.merchant_subscriptions
  for select using (user_id = auth.uid() or public.is_admin());
-- Active store subscriptions are public so the store directory can list them.
create policy merchant_subscriptions_select_active_stores on public.merchant_subscriptions
  for select using (status = 'active' and can_use_store);
create policy merchant_subscriptions_admin_write on public.merchant_subscriptions
  for all using (public.is_admin()) with check (public.is_admin());

create trigger merchant_subscriptions_updated_at
  before update on public.merchant_subscriptions
  for each row execute function public.set_updated_at();

create or replace view public.public_stores
with (security_invoker = true) as
select distinct on (p.id)
  p.id as merchant_id,
  coalesce(p.full_name, p.username) as name,
  s.max_products
from public.profiles p
join public.merchant_subscriptions s on s.user_id = p.id
where p.role = 'merchant'
  and p.merchant_status = 'active'
  and s.status = 'active'
  and s.can_use_store
order by p.id, s.created_at desc;

grant select on public.public_stores to anon, authenticated;

