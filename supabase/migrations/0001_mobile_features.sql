create table if not exists public.report_cases (
  id uuid primary key default gen_random_uuid(),
  reporter_user_id uuid not null references public.profiles(id) on delete cascade,
  listing_id uuid references public.listings(id) on delete set null,
  subject text not null check (char_length(subject) between 3 and 120),
  details text not null check (char_length(details) between 10 and 1000),
  status text not null default 'open' check (status in ('open', 'reviewing', 'resolved', 'dismissed')),
  priority text not null default 'medium' check (priority in ('low', 'medium', 'high')),
  reviewer_user_id uuid references public.profiles(id) on delete set null,
  resolution text check (resolution is null or char_length(resolution) <= 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists report_cases_status_idx on public.report_cases (status, priority, created_at desc);
alter table public.report_cases enable row level security;

create policy report_cases_insert_own on public.report_cases
  for insert with check (reporter_user_id = auth.uid() and status = 'open' and reviewer_user_id is null and resolution is null);
create policy report_cases_select_own_or_admin on public.report_cases
  for select using (reporter_user_id = auth.uid() or public.is_admin());
create policy report_cases_admin_update on public.report_cases
  for update using (public.is_admin()) with check (public.is_admin());

