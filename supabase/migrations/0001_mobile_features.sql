-- ---------------------------------------------------------------------
-- 6) Store chats (same rule as the original app: only with active stores)
-- ---------------------------------------------------------------------
create table if not exists public.store_conversations (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid references public.listings(id) on delete set null,
  buyer_user_id uuid not null references public.profiles(id) on delete cascade,
  merchant_user_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'active' check (status in ('active', 'closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (buyer_user_id <> merchant_user_id)
);
create index if not exists store_conversations_buyer_idx on public.store_conversations (buyer_user_id, updated_at desc);
create index if not exists store_conversations_merchant_idx on public.store_conversations (merchant_user_id, updated_at desc);
alter table public.store_conversations enable row level security;

create policy store_conversations_select_participants on public.store_conversations
  for select using (auth.uid() in (buyer_user_id, merchant_user_id) or public.is_admin());
create policy store_conversations_insert_buyer on public.store_conversations
  for insert with check (
    buyer_user_id = auth.uid()
    and status = 'active'
    and exists (
      select 1 from public.listings l
      where l.id = store_conversations.listing_id
        and l.status = 'active'
        and l.user_id = store_conversations.merchant_user_id
    )
    and exists (select 1 from public.public_stores s where s.merchant_id = store_conversations.merchant_user_id)
  );

create table if not exists public.store_messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.store_conversations(id) on delete cascade,
  sender_user_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(btrim(body)) between 1 and 2000),
  read_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists store_messages_conversation_idx on public.store_messages (conversation_id, created_at);
alter table public.store_messages enable row level security;

create policy store_messages_select_participants on public.store_messages
  for select using (exists (
    select 1 from public.store_conversations c
    where c.id = store_messages.conversation_id and auth.uid() in (c.buyer_user_id, c.merchant_user_id)
  ));
-- Buyer can always write; merchant needs an active subscription with chat replies.
create policy store_messages_insert_participant on public.store_messages
  for insert with check (
    sender_user_id = auth.uid()
    and exists (
      select 1 from public.store_conversations c
      where c.id = store_messages.conversation_id
        and c.status = 'active'
        and (
          c.buyer_user_id = auth.uid()
          or (c.merchant_user_id = auth.uid() and exists (
            select 1 from public.merchant_subscriptions s
            where s.user_id = auth.uid() and s.status = 'active' and s.can_reply_to_chats
          ))
        )
    )
  );

create or replace function public.on_store_message()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  conv public.store_conversations%rowtype;
  recipient uuid;
begin
  select * into conv from public.store_conversations where id = new.conversation_id;
  update public.store_conversations set updated_at = now() where id = new.conversation_id;
  recipient := case when new.sender_user_id = conv.buyer_user_id then conv.merchant_user_id else conv.buyer_user_id end;
  insert into public.notifications (user_id, type, title, body, listing_id)
  values (recipient, 'chat_message', 'رسالة جديدة', left(new.body, 140), conv.listing_id);
  return new;
end;
$$;

create trigger store_messages_after_insert
  after insert on public.store_messages
  for each row execute function public.on_store_message();

